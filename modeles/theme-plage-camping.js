  // Bande d'ombre : une perle dont la lettre est dans `carte` prend le ton foncé si le vide
  // est à moins de `nd` perles à sa droite, ou à moins de `nb` perles en dessous.
  function ombre(lignes, carte, nd = 2, nb = 1) {
    const w = Math.max(...lignes.map((l) => l.length)), h = lignes.length;
    const g = lignes.map((l) => l.padEnd(w, '.'));
    const vide = (x, y) => y >= h || x >= w || g[y][x] === '.';
    return g.map((r, y) => [...r].map((c, x) => {
      if (!carte[c]) return c;
      for (let k = 1; k <= nd; k++) if (vide(x + k, y)) return carte[c];
      for (let k = 1; k <= nb; k++) if (vide(x, y + k)) return carte[c];
      return c;
    }).join(''));
  }

