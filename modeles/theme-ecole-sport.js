  function cerner(lignes) {
    const w = Math.max(...lignes.map((l) => l.length)) + 2;
    const g = ['', ...lignes, ''].map((l) => ('.' + l).padEnd(w, '.').split(''));
    const h = g.length;
    const plein = (x, y) => y >= 0 && y < h && x >= 0 && x < w && g[y][x] !== '.' && g[y][x] !== '#';
    const res = g.map((r) => r.slice());
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (g[y][x] === '.' && (plein(x - 1, y) || plein(x + 1, y) || plein(x, y - 1) || plein(x, y + 1))) res[y][x] = 'K';
    }
    return res.map((r) => r.join('').replace(/#/g, 'K'));
  }
  // moitié gauche (colonne du milieu comprise, sauf si `pair`) → sujet entier ; `remplace` ne touche que la moitié droite
  function sym(moitie, remplace = {}, pair = false) {
    return moitie.map((l) => l + [...(pair ? l : l.slice(0, -1))].reverse().map((c) => remplace[c] || c).join(''));
  }
  // ombre en bordure : une perle prend son ton foncé si le vide (« . ») est à moins de `ep` perles à sa droite
  // ou de `epBas` perles en dessous
  function ombrer(lignes, ombre, ep = 2, epBas = ep) {
    const h = lignes.length, vide = (x, y) => y >= h || x >= lignes[y].length || lignes[y][x] === '.';
    return lignes.map((l, y) => [...l].map((c, x) => {
      if (!ombre[c]) return c;
      for (let d = 1; d <= ep; d++) if (vide(x + d, y)) return ombre[c];
      for (let d = 1; d <= epBas; d++) if (vide(x, y + d)) return ombre[c];
      return c;
    }).join(''));
  }
