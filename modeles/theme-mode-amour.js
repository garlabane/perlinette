// On dessine l'INTÉRIEUR du sujet ; `cerner` ajoute tout autour le contour noir continu d'une perle.
// `miroir` recopie la moitié gauche (colonne du milieu comprise) ; `carte` remet les touches
// claires de droite au ton de base (la lumière vient d'en haut à gauche) ; `ajouts` = retouches.
// `ombrer` pose l'ombre en BORDURE : une bande de `ep` perles du ton foncé le long du bord droit
