  function cerner(lignes) {
    const w = Math.max(...lignes.map((l) => l.length)) + 2;
    const g = ['', ...lignes, ''].map((l) => ('.' + l).padEnd(w, '.').split(''));
    const h = g.length;
    const plein = (x, y) => y >= 0 && y < h && x >= 0 && x < w && g[y][x] !== '.' && g[y][x] !== '#';
    const res = g.map((r) => r.slice());
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (g[y][x] === '.' && (plein(x - 1, y) || plein(x + 1, y) || plein(x, y - 1) || plein(x, y + 1))) res[y][x] = 'K';
    }
    return res.map((r) => r.join('').replace(/#/g, 'K'));
  }

  function miroir(gauche, carte = {}, ajouts = []) {
    const n = Math.max(...gauche.map((l) => l.length));
    const g = gauche.map((l) => {
      l = l.padEnd(n, '.');
      return l + [...l.slice(0, -1)].reverse().map((c) => carte[c] || c).join('');
    });
    for (const [y, x, s] of ajouts) g[y] = g[y].slice(0, x) + s + g[y].slice(x + s.length);
    return g;
  }

  function ombrer(lignes, carte, ep = 2) {
    const h = lignes.length, w = Math.max(...lignes.map((l) => l.length));
    const vide = (x, y) => y < 0 || y >= h || x < 0 || x >= w || !lignes[y][x] || lignes[y][x] === '.' || lignes[y][x] === '#';
    return lignes.map((l, y) => [...l].map((c, x) => {
      if (!carte[c]) return c;
      for (let d = 1; d <= ep; d++) if (vide(x + d, y) || vide(x, y + d)) return carte[c];
      return vide(x + 1, y + 1) ? carte[c] : c;
    }).join(''));
  }

