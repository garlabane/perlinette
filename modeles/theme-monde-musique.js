  // moins de `n` perles à sa droite ou en dessous (bande qui suit la forme, côté opposé à la lumière).
  function ombrer(lignes, paires, n = 2) {
    const h = lignes.length, w = Math.max(...lignes.map((l) => l.length));
    const vide = (x, y) => y >= h || x >= w || (lignes[y][x] || '.') === '.';
    return lignes.map((l, y) => [...l].map((c, x) => {
      if (!paires[c]) return c;
      for (let d = 1; d <= n; d++) if (vide(x + d, y) || vide(x, y + d)) return paires[c];
      return c;
    }).join(''));
  }
